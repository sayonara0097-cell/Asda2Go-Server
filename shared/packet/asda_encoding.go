package packet

import "asda2/shared/crypt"

var (
	asdaRuChars = []rune("йцукенгшщзхъфывапролджэячсмитьбюЙЦУКЕНГШЩЗХЪФЫВАПРОЛДЖЭЯЧСМИТЬБЮёЁ")
	asdaRuBytes = []byte{
		0xE9, 0xF6, 0xF3, 0xEA, 0xE5, 0xED, 0xE3, 0xF8, 0xF9, 0xE7, 0xF5, 0xFA,
		0xF4, 0xFB, 0xE2, 0xE0, 0xEF, 0xF0, 0xEE, 0xEB, 0xE4, 0xE6, 0xFD, 0xFF,
		0xF7, 0xF1, 0xEC, 0xE8, 0xF2, 0xFC, 0xE1, 0xFE, 0xC9, 0xD6, 0xD3, 0xCA,
		0xC5, 0xCD, 0xC3, 0xD8, 0xD9, 0xC7, 0xD5, 0xDA, 0xD4, 0xDB, 0xC2, 0xC0,
		0xCF, 0xD0, 0xCE, 0xCB, 0xC4, 0xC6, 0xDD, 0xDF, 0xD7, 0xD1, 0xCC, 0xC8,
		0xD2, 0xDC, 0xC1, 0xDE, 0xB8, 0xA8,
	}
	asdaArChars = []rune("ضصثقفغعهخحجدشسيبلاتنمكطئءؤرلاىةوزظذلآآ,.><أإ،؛؟ـپچژگک")
	asdaArBytes = []byte{
		0xD6, 0xD5, 0xCB, 0xDE, 0xDD, 0xDB, 0xDA, 0xE5, 0xCE, 0xCD, 0xCC, 0xCF,
		0xD4, 0xD3, 0xED, 0xC8, 0xE1, 0xC7, 0xCA, 0xE4, 0xE3, 0xDF, 0xD8, 0xC6,
		0xC1, 0xC4, 0xD1, 0xE1, 0xC7, 0xEC, 0xC9, 0xE6, 0xD2, 0xD9, 0xD0, 0xE1,
		0xC2, 0xC2, 0x2C, 0x2E, 0x3E, 0x3C, 0xC3, 0xC5, 0xA1, 0xBA, 0xBF, 0xDC,
		0x81, 0x8D, 0x8E, 0x90, 0x98,
	}

	asdaRuDecode [256]rune
	asdaArDecode [256]rune
	asdaRuEncode map[rune]byte
	asdaArEncode map[rune]byte
)

func init() {
	asdaRuEncode = make(map[rune]byte, 256+len(asdaRuChars))
	asdaArEncode = make(map[rune]byte, 256+len(asdaArChars))
	for i := 0; i < 256; i++ {
		asdaRuDecode[i] = rune(i)
		asdaArDecode[i] = rune(i)
		asdaRuEncode[rune(i)] = byte(i)
		asdaArEncode[rune(i)] = byte(i)
	}
	for i, r := range asdaRuChars {
		b := asdaRuBytes[i]
		asdaRuDecode[b] = r
		asdaRuEncode[r] = b
	}
	for i, r := range asdaArChars {
		b := asdaArBytes[i]
		asdaArDecode[b] = r
		asdaArEncode[r] = b
	}
}

func encodeAsdaString(s string, locale crypt.Locale) []byte {
	encode := asdaArEncode
	if locale == crypt.LocaleRu {
		encode = asdaRuEncode
	}
	out := make([]byte, 0, len(s))
	for _, r := range s {
		if b, ok := encode[r]; ok {
			out = append(out, b)
			continue
		}
		out = append(out, '?')
	}
	return out
}

func decodeAsdaString(data []byte, locale crypt.Locale) string {
	decode := &asdaArDecode
	if locale == crypt.LocaleRu {
		decode = &asdaRuDecode
	}
	out := make([]rune, len(data))
	for i, b := range data {
		out[i] = decode[b]
	}
	return string(out)
}
